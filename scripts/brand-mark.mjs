// Single source for the Parkline mark: a scalloped badge with a line-art car.
// Usage: node scripts/brand-mark.mjs  -> writes the SVG, Android vectors and favicon sources.
import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

export const colors = { night: "#191c19", badge: "#22261f", ink: "#fff1d6", gold: "#ffc776" };

/** Scalloped outline (10 soft lobes) as an SVG path centred on (cx, cy). */
export function scallop(cx, cy, radius, depth = 0.055, lobes = 10, steps = 240) {
  const points = [];
  for (let i = 0; i < steps; i++) {
    const t = (i / steps) * Math.PI * 2 - Math.PI / 2;
    const r = radius * (1 + depth * Math.cos(lobes * t));
    points.push(`${(cx + r * Math.cos(t)).toFixed(2)} ${(cy + r * Math.sin(t)).toFixed(2)}`);
  }
  return `M${points.join("L")}Z`;
}

// Car drawn on a 24-unit grid, facing right; centred around (12.2, 12.45).
export const car = {
  body: "M4.9 16H3.6a1.1 1.1 0 0 1-1.1-1.1V13c0-.8.5-1.4 1.3-1.6l2.5-.6L9 7.6c.4-.5 1-.8 1.6-.8h4.2c.6 0 1.2.3 1.6.7l3 3.3 1.5.4c.9.2 1.5 1 1.5 1.9v1.8a1.1 1.1 0 0 1-1.1 1.1h-1.1M9.1 16h6",
  glass: "M6.6 10.8h12.8M13 6.9v3.9",
  wheels: [[7, 16], [17.2, 16]],
  wheelRadius: 2.1,
  centre: [12.2, 12.45],
};

/** Full mark as SVG markup on a square canvas. */
export function svg(size = 512, { background = null, badge = true, small = false } = {}) {
  const c = size / 2;
  const scale = size / (small ? 34 : 37);
  const [gx, gy] = car.centre;
  const stroke = small ? 2.4 : 1.75;
  const wheels = car.wheels.map(([x, y]) => `<circle cx="${x}" cy="${y}" r="${car.wheelRadius}"/>`).join("");
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${size} ${size}" width="${size}" height="${size}">` +
    (background ? `<rect width="${size}" height="${size}" fill="${background}"/>` : "") +
    (badge ? `<path d="${scallop(c, c, size * 0.43)}" fill="${colors.badge}" stroke="${colors.ink}" stroke-width="${(size * (small ? 0.05 : 0.028)).toFixed(2)}" stroke-linejoin="round"/>` : "") +
    `<g transform="translate(${(c - gx * scale).toFixed(2)} ${(c - gy * scale).toFixed(2)}) scale(${scale.toFixed(4)})" fill="none" stroke="${colors.gold}" stroke-width="${stroke}" stroke-linecap="round" stroke-linejoin="round">` +
    `<path d="${car.body}"/><path d="${car.glass}"/>${wheels}</g></svg>`;
}

/** Android VectorDrawable of the mark. `viewport` 108 = adaptive-icon layer, 48 = legacy icon. */
function vector(viewport, { badgeRadius, carScale, badge = true, tint = null }) {
  const c = viewport / 2;
  const [gx, gy] = car.centre;
  const circle = ([x, y], r) => `M${x - r},${y}a${r},${r} 0 1,0 ${r * 2},0a${r},${r} 0 1,0 ${-r * 2},0`;
  const strokeColor = tint ?? colors.gold;
  const lines = [car.body, car.glass, ...car.wheels.map((w) => circle(w, car.wheelRadius))]
    .map((d) => `        <path android:pathData="${d}" android:strokeColor="${strokeColor}" android:strokeWidth="1.75" android:strokeLineCap="round" android:strokeLineJoin="round" android:fillColor="#00000000"/>`).join("\n");
  const shape = badge
    ? `    <path android:pathData="${scallop(c, c, badgeRadius)}" android:fillColor="${tint ? "#00000000" : colors.badge}" android:strokeColor="${tint ?? colors.ink}" android:strokeWidth="${(badgeRadius * 0.065).toFixed(2)}" android:strokeLineJoin="round"/>\n`
    : "";
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/brand-mark.mjs: edit the script, not this file. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="${viewport}dp" android:height="${viewport}dp"
    android:viewportWidth="${viewport}" android:viewportHeight="${viewport}">
${shape}    <group android:scaleX="${carScale}" android:scaleY="${carScale}"
        android:translateX="${(c - gx * carScale).toFixed(3)}" android:translateY="${(c - gy * carScale).toFixed(3)}">
${lines}
    </group>
</vector>
`;
}

if (import.meta.url === `file:///${process.argv[1].replaceAll("\\", "/")}` || process.argv[1]?.endsWith("brand-mark.mjs")) {
  const root = process.cwd();
  const res = join(root, "android", "app", "src", "main", "res");
  const write = (path, text) => { mkdirSync(join(path, ".."), { recursive: true }); writeFileSync(path, text); };

  write(join(root, "app", "icon.svg"), svg(512));
  write(join(root, "public", "parkline-mark.svg"), svg(512));
  // Adaptive icon: the launcher masks a 108dp layer to its own shape; keep the badge inside the 66dp safe zone.
  write(join(res, "drawable", "ic_parkline_foreground.xml"), vector(108, { badgeRadius: 30, carScale: 2.15 }));
  write(join(res, "drawable", "ic_parkline_monochrome.xml"), vector(108, { badgeRadius: 30, carScale: 2.15, tint: "#ffffff" }));
  // Legacy (Android 7) and splash: the whole badge fills most of the canvas.
  write(join(res, "drawable", "ic_parkline_badge.xml"), vector(48, { badgeRadius: 20.5, carScale: 1.48 }));
  console.log("Brand mark written.");
}
